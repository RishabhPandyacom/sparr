import type {
  AiProvider,
  GenerateStructuredInput,
  GenerateTextInput,
  GenerateTextResult,
} from "../types";

/**
 * Deterministic, offline provider. Returns realistic canned responses so the
 * entire app is demoable with no API key. Output is intentionally templated
 * from the caller's context (company, role, etc.) so it feels tailored — but
 * it is NOT a real LLM. Swap in a real provider via AI_PROVIDER=anthropic|openai.
 */
export class MockAiProvider implements AiProvider {
  readonly name = "mock";
  private readonly model = "mock-1";

  async generateText(input: GenerateTextInput): Promise<GenerateTextResult> {
    // Tiny delay so loading states are visible in the UI.
    await delay(500);
    const content = this.render(input);
    return { content, provider: this.name, model: this.model };
  }

  async generateStructured<T>(input: GenerateStructuredInput): Promise<T> {
    await delay(500);
    return this.renderStructured(input) as T;
  }

  private lastUserMessage(input: GenerateTextInput): string {
    const users = input.messages.filter((m) => m.role === "user");
    return users.length ? users[users.length - 1].content : "";
  }

  private render(input: GenerateTextInput): string {
    const ctx = input.mockContext ?? {};
    switch (input.mockHint) {
      case "cover_letter":
        return mockCoverLetter(ctx);
      case "interview_question":
        return mockInterviewQuestion(ctx);
      case "interview_feedback":
        return mockInterviewFeedback(ctx);
      case "salary_negotiation":
        return mockSalaryScript(ctx);
      default:
        return (
          "This is a mock AI response. Configure a real provider " +
          "(AI_PROVIDER=anthropic or openai) to get live output.\n\n" +
          `You asked: ${truncate(this.lastUserMessage(input), 200)}`
        );
    }
  }

  private renderStructured(input: GenerateStructuredInput): unknown {
    switch (input.mockHint) {
      case "mcq_questions":
        return { questions: mockMcqQuestions(input.mockContext ?? {}) };
      case "code_review":
        return mockCodeReview();
      default:
        return {};
    }
  }
}

function delay(ms: number) {
  return new Promise((r) => setTimeout(r, ms));
}

function truncate(s: string, n: number) {
  return s.length > n ? `${s.slice(0, n)}…` : s;
}

// ── Canned generators ───────────────────────────────────────────────────────

function mockCoverLetter(ctx: Record<string, string | undefined>) {
  const company = ctx.company || "your company";
  const role = ctx.role || "the role";
  const name = ctx.name || "A. Candidate";
  return `Dear Hiring Manager,

I'm excited to apply for ${role} at ${company}. When I read the job description, it struck me how closely the responsibilities map to what I already love doing — building things that matter and shipping them end to end.

In my most recent work I focused on impact over activity: I looked for the highest-leverage problems, learned quickly, and communicated clearly with everyone involved. Those are the same instincts I'd bring to ${company} from day one.

What draws me to ${company} specifically is the chance to grow while contributing to work that reaches real users. I'd welcome the opportunity to discuss how my background lines up with what your team needs.

Thank you for your time and consideration.

Sincerely,
${name}

— (Draft generated by the mock AI provider. Connect a real LLM key to tailor this to the exact job description.)`;
}

function mockInterviewQuestion(ctx: Record<string, string | undefined>) {
  const topic = ctx.topic || "your background";
  return `Thanks for that. Let's go a level deeper on ${topic}. Can you walk me through a specific situation where you faced a real constraint — time, resources, or ambiguity — and describe how you approached it, what tradeoffs you weighed, and what the outcome was?`;
}

